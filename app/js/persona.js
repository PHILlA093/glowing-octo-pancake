/* ---------- 组装发给模型的 system prompt ---------- */
function buildSystemPrompt(companion, ctx) {
  const c = COMPANIONS.find(x => x.id === companion) || COMPANIONS[0];
  const now = ctx && ctx.now ? ctx.now : new Date();
  const hour = now.getHours();
  const phase = hour < 5 ? '凌晨' : hour < 11 ? '早上' : hour < 14 ? '中午'
    : hour < 18 ? '下午' : hour < 23 ? '晚上' : '深夜';

  const parts = [
    IRON_RULES,
    '',
    `【你现在的身份】你叫「${c.name}」。${c.style.trim()}`,
    '',
    `【此刻】现在是${phase}（${hour} 点）。如果这个时间点本身会让人更难受（比如深夜、凌晨），你可以自然地带一句，但不要说教他早睡。`,
  ];

  // 记忆只用于让他此刻更舒服，绝不翻旧账
  const likes = ctx && ctx.likes ? ctx.likes : [];
  if (likes.length) {
    parts.push('', `【你记得他的偏好】${likes.slice(0, 8).join('；')}`);
    parts.push('注意：这些偏好只在自然地让他舒服时才用。不要主动提起他过去的痛苦经历。');
  }

  parts.push('', `【再次强调】不用问句。不追问。不分析。不建议。短。你只是陪着。`);
  return parts.join('\n');
}

