const OPENING_GREETINGS = {
  dawn: ['还没睡。我在。', '这个点还醒着，不容易。我不问你为什么。'],
  morning: ['早。今天不用急着好起来。', '早，今天也在。'],
  noon: ['中午了。歇一会儿也行。', '在的。'],
  afternoon: ['下午了。累了就停一下。', '在。'],
  evening: ['晚上了。今天辛苦了。', '回来了就好。'],
  night: ['夜深了。我在。', '这个点最容易难熬。我在。']
};

function openingGreeting(now) {
  const h = (now || new Date()).getHours();
  const key = h < 5 ? 'dawn' : h < 11 ? 'morning' : h < 14 ? 'noon'
    : h < 18 ? 'afternoon' : h < 23 ? 'evening' : 'night';
  const list = OPENING_GREETINGS[key];
  return list[Math.floor(Math.random() * list.length)];
}

/* ---------- 危机识别（本地兜底，与提示词双保险） ---------- */
const CRISIS_PATTERNS = [
  /不想活/, /活不下去/, /活着没(什么)?意思/, /活够了/,
  /想死/, /去死/, /自杀/, /结束(自己的)?生命/, /了结/,
  /不想(再)?醒(来|过)/, /消失(掉|了)?就好/, /没有我(会)?更好/,
  /割(腕|手)/, /跳(楼|下去|河)/, /安眠药.*(吃|吞)/, /上吊/,
  /解脱(了)?$/, /撑不下去(了)?/, /熬不下去/, /不想(再)?撑/
];

function detectCrisis(text) {
  if (!text) return false;
  const t = String(text).replace(/\s+/g, '');
  return CRISIS_PATTERNS.some(re => re.test(t));
}

